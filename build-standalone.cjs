// Build classic-script bundles so both browser entries work from file:// without a server.
// Source modules remain the editable development version.
const fs = require('node:fs');
const path = require('node:path');

const root = __dirname;
const levelJson = fs.readFileSync(path.join(root, 'massage_mayhem_engine/levels.json'), 'utf8').trim();
JSON.parse(levelJson); // Fail before producing a bundle if a level edit broke JSON.
fs.writeFileSync(path.join(root, 'massage_mayhem_engine/levels-data.js'), `export default ${levelJson};\n`);
const entries = [
  ['massage_mayhem_engine/campaign.js', 'massage_mayhem_engine/play-bundle.js'],
  ['animation-experience/main.js', 'animation-experience/animation-bundle.js']
];

function build(entry, output) {
  const modules = new Map();
  const key = file => path.relative(root, file).replaceAll('\\', '/');
  function visit(file) {
    const abs = path.resolve(root, file);
    const id = key(abs);
    if (modules.has(id)) return id;
    let source = fs.readFileSync(abs, 'utf8');
    const dependencies = [];
    source = source.replace(/^\s*import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"]\s*;?/gm, (_, bindings, specifier) => {
      const target = path.resolve(path.dirname(abs), specifier);
      const dep = key(target); dependencies.push(target);
      const names = bindings.trim();
      if (names.startsWith('{')) return `const ${names} = __require(${JSON.stringify(dep)});`;
      if (/^[A-Za-z_$][\w$]*$/.test(names)) return `const ${names} = __require(${JSON.stringify(dep)}).default;`;
      throw Error(`Unsupported import in ${id}: ${names}`);
    });
    source = source.replace(/^\s*export\s+\*\s+from\s+['"]([^'"]+)['"]\s*;?/gm, (_, specifier) => {
      const target = path.resolve(path.dirname(abs), specifier);
      const dep = key(target); dependencies.push(target);
      return `Object.assign(exports, __require(${JSON.stringify(dep)}));`;
    });
    const exposed = [];
    source = source.replace(/\bexport\s+(const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/g, (_, kind, name) => {
      exposed.push(name); return `${kind} ${name}`;
    });
    source = source.replace(/\bexport\s+default\s+/g, 'exports.default = ');
    if (/\b(?:import|export)\s/.test(source)) throw Error(`Unprocessed module syntax in ${id}`);
    source += `\n${exposed.map(name => `exports.${name} = ${name};`).join('\n')}`;
    modules.set(id, source);
    for (const dependency of dependencies) visit(dependency);
    return id;
  }
  const entryId = visit(entry);
  let result = '/* Generated by build-standalone.cjs. Edit source modules, then rebuild. */\n(()=>{\n"use strict";\nconst __factories = Object.create(null);\n';
  for (const [id, source] of modules) result += `__factories[${JSON.stringify(id)}] = function(exports, __require){\n${source}\n};\n`;
  result += `const __cache = Object.create(null);\nfunction __require(id){ if(__cache[id]) return __cache[id].exports; const factory=__factories[id]; if(!factory) throw Error('Missing module '+id); const module={exports:{}}; __cache[id]=module; factory(module.exports,__require); return module.exports; }\n__require(${JSON.stringify(entryId)});\n})();\n`;
  fs.writeFileSync(path.resolve(root, output), result);
  console.log(`${output}: ${modules.size} modules, ${Buffer.byteLength(result)} bytes`);
}

for (const [entry, output] of entries) build(entry, output);
