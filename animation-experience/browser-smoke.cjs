const { pathToFileURL } = require('node:url');
const path = require('node:path');
const fs = require('node:fs');
let chromium;
try { ({ chromium } = require('playwright')); }
catch {
  const bundled = path.join(process.env.USERPROFILE || '', '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
  ({ chromium } = require(bundled));
}

(async () => {
  const chrome = process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
  const browser = await chromium.launch({ headless: true, ...(fs.existsSync(chrome) ? { executablePath: chrome } : {}), args: process.env.NO_FILE_FLAG ? [] : ['--allow-file-access-from-files'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.join(__dirname, 'index.html')).href);
  await page.waitForFunction(() => window.animationQA?.state?.pose?.rightHand, { timeout: 10000 });
  const ready = () => page.waitForFunction(() => window.animationQA.state.frame.phase === 'observe');
  await ready();
  const clickZone = async (x = 603, y = 342) => {
    await page.locator('#stage').scrollIntoViewIfNeeded();
    const rect = await page.locator('#stage').boundingBox();
    await page.mouse.click(rect.x + rect.width * x / 960, rect.y + rect.height * y / 540);
  };
  await clickZone();
  await page.waitForTimeout(1200);
  const first = await page.evaluate(() => ({ battle: window.animationQA.state.battle, frame: window.animationQA.state.frame, pose: window.animationQA.state.pose }));
  if (first.battle.turns !== 1) throw Error(`click did not commit once: ${first.battle.turns}`);
  const castIds = ['charming_m','charming_f','uncle','aunt','gentle','power','joker','bao_master'];
  if (await page.locator('[data-group="cast"] button').count() !== castIds.length) throw Error('eight technicians are not selectable');
  for (const id of castIds) {
    await page.locator(`[data-group="cast"] [data-id="${id}"]`).click();
    if (id === 'bao_master') await page.locator('[data-group="scene"] [data-id="feet"]').click();
    const state = await page.evaluate(() => window.animationQA.state);
    if (state.battle.therapistId !== id || !state.pose?.rightHand) throw Error(`cast ${id} did not render`);
    if (await page.locator('#inventory button[data-id]').count() < 2) throw Error(`cast ${id} has no tools`);
    await page.locator('#signature').click();
    await page.waitForFunction(() => window.animationQA.state.battle.energy === 0, { timeout: 3500 });
  }
  await page.locator('[data-group="cast"] [data-id="bao_master"]').click();
  await page.locator('[data-group="scene"] [data-id="back"]').click();
  await page.locator('#inventory button[data-id="basin"]').click();
  await page.waitForFunction(() => window.animationQA.state.frame.tool === 'basin' && window.animationQA.state.battle.scene === 'feet');
  if (!(await page.locator('#feedback').textContent()).includes('木质泡脚盆')) throw Error('cross-scene prop was not selected');
  await page.locator('[data-group="scene"] [data-id="back"]').click();
  await page.locator('#signature').click();
  await page.waitForFunction(() => window.animationQA.state.battle.scene === 'feet' && window.animationQA.state.frame.signature);
  await page.locator('[data-group="cast"] [data-id="bao_master"]').click();
  await page.locator('#jolt').click();
  if ((await page.evaluate(() => window.animationQA.state.frame.phase)) !== 'interrupted') throw Error('idle jolt gave no reaction');
  await page.locator('[data-group="cast"] [data-id="aunt"]').click();
  await page.locator('[data-group="scene"] [data-id="feet"]').click();
  await ready();
  const foot = await page.evaluate(() => window.animationQA.state);
  if (foot.battle.therapistId !== 'aunt' || foot.battle.scene !== 'feet') throw Error('cast/scene switch failed');
  await page.screenshot({ path: path.join(__dirname, 'qa-stage.png'), fullPage: false });
  await page.locator('[data-group="tool"] [data-id="towel"]').click();
  await ready();
  await page.locator('#stage').scrollIntoViewIfNeeded();
  const footRect = await page.locator('#stage').boundingBox();
  await page.mouse.move(footRect.x + footRect.width * 600 / 960, footRect.y + footRect.height * 389 / 540);
  await page.mouse.down(); await page.waitForTimeout(550);
  await page.mouse.move(footRect.x + footRect.width * 632 / 960, footRect.y + footRect.height * 399 / 540, { steps: 10 });
  const dragging = await page.evaluate(() => window.animationQA.state);
  if (!dragging.frame.contactActive || dragging.frame.target.x < 625 || dragging.frame.tool !== 'towel') throw Error('hold/drag/tool did not bind');
  await page.locator('#jolt').click(); await page.mouse.up(); await page.waitForTimeout(850);
  const interrupted = await page.evaluate(() => window.animationQA.state);
  if (interrupted.frame.contactActive || interrupted.battle.turns !== 1) throw Error('jolt failed to stop/contact commit');
  const contacts = [];
  for (const [technician, targetScene, x, y] of [['charming_m','back',683,342],['aunt','feet',678,389],['bao_master','feet',678,389]]) {
    await page.locator(`[data-group="cast"] [data-id="${technician}"]`).click();
    await page.locator(`[data-group="scene"] [data-id="${targetScene}"]`).click();
    await ready();
    await page.locator('#stage').scrollIntoViewIfNeeded();
    const rect = await page.locator('#stage').boundingBox();
    await page.mouse.move(rect.x + rect.width * x / 960, rect.y + rect.height * y / 540);
    await page.mouse.down(); await page.waitForTimeout(650);
    const contact = await page.evaluate(() => window.animationQA.state);
    const error = Math.hypot(contact.pose.rightHand.x - contact.pose.target.x, contact.pose.rightHand.y - contact.pose.target.y);
    contacts.push({ technician, scene: targetScene, error: Math.round(error * 10) / 10 });
    if (!contact.frame.contactActive || error > 12) throw Error(`contact miss ${technician}/${targetScene}: ${error} ${JSON.stringify({frame:contact.frame,pose:contact.pose})}`);
    await page.mouse.up(); await page.waitForTimeout(750);
  }
  await page.locator('[data-group="cast"] [data-id="bao_master"]').click();
  await page.locator('[data-group="scene"] [data-id="feet"]').click();
  await ready();
  await page.locator('#signature').click();
  await page.waitForTimeout(2500);
  const bao = await page.evaluate(() => window.animationQA.state);
  if (bao.battle.energy !== 0 || bao.battle.comfort < 30) throw Error('Bao skill/rules not synchronized');
  await page.locator('#signature').click();
  await page.waitForFunction(() => window.animationQA.state.battle.comfort >= 60 && window.animationQA.state.battle.energy === 0, { timeout: 3500 });
  const baoInventory = await page.locator('#inventory button[data-id]').count();
  if (baoInventory !== 21) throw Error(`Bao inventory should show hand + 20 items, saw ${baoInventory}`);
  await page.screenshot({ path: path.join(__dirname, 'qa-bao-inventory.png'), fullPage: true });
  await page.locator('#reset').click(); await ready();
  await page.locator('#inventory button[data-id="towel"]').click();
  await page.locator('#inventory button[data-id="oil"]').click();
  await page.waitForFunction(() => window.animationQA.state.frame.tool === 'oil' && window.animationQA.state.frame.toolHeld && window.animationQA.state.frame.phase === 'observe', { timeout: 3500 });
  await page.locator('#reset').click(); await ready();
  await page.locator('#inventory button[data-id="cake"]').click(); await ready();
  await clickZone(507, 222); await page.waitForTimeout(1150);
  const food = await page.evaluate(() => window.animationQA.state.battle);
  if (food.turns !== 1 || food.spentCoins !== 10 || !food.log.some(e => e.message?.includes('美食招待'))) throw Error('cake did not run food service');
  await page.locator('[data-group="scene"] [data-id="back"]').click(); await ready();
  await page.locator('#inventory button[data-id="durian"]').click(); await ready();
  await clickZone(); await page.waitForTimeout(1150);
  const prank = await page.evaluate(() => window.animationQA.state.battle);
  if (prank.turns !== 1 || !prank.log.some(e => e.message?.includes('卡通整蛊'))) throw Error('durian did not run prank service');
  await page.setViewportSize({ width: 390, height: 844 });
  const mobile = await page.evaluate(() => ({ content: document.documentElement.scrollWidth, viewport: document.documentElement.clientWidth }));
  if (mobile.content > mobile.viewport) throw Error(`mobile horizontal overflow: ${mobile.content} > ${mobile.viewport}`);
  if (errors.length) throw Error(`browser errors: ${errors.join(' | ')}`);
  console.log(JSON.stringify({ castCount: castIds.length, clickTurns: first.battle.turns, draggedTargetX: dragging.frame.target.x, joltTurns: interrupted.battle.turns, contactErrors: contacts, baoInventory, cakeCost: food.spentCoins, durianTurns: prank.turns, baoComfort: bao.battle.comfort, baoEnergy: bao.battle.energy, mobile, browserErrors: errors.length }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
